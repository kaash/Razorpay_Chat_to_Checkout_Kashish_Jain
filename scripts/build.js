#!/usr/bin/env node
"use strict";
// Builds the single-file page and the shared server module from frontend/src.
//   public/index.html  ← the prototype (same UI as the submitted HTML)
//   lib/core.js        ← the price list, rules parser and pricing code, shared with the server
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, ".."), src = path.join(root, "frontend", "src");
const read = f => fs.readFileSync(path.join(src, f), "utf8");
const js = ["3-data-parser.js", "4-copy.js", "5-ui.js", "6-demo.js", "7-live.js", "8-init.js"].map(read).join("\n");
const html = read("1-head.html") + read("2-body.html") + "<script>\n" + js + "</script>\n</body>\n</html>\n";
fs.mkdirSync(path.join(root, "public"), { recursive: true });
fs.writeFileSync(path.join(root, "public", "index.html"), html);
const core = "// GENERATED by scripts/build.js from frontend/src/3-data-parser.js. Edit the source, then run npm run build.\n" + read("3-data-parser.js") + "\nmodule.exports = { DATA, P, compute, replyText, followText, toSchema, rs };\n";
fs.writeFileSync(path.join(root, "lib", "core.js"), core);
console.log(`public/index.html ${(html.length / 1024).toFixed(0)} KB · lib/core.js ${(core.length / 1024).toFixed(0)} KB`);
